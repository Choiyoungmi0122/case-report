/**
 * True when the visits are exactly the fixed virtual-patient case. That record is
 * synthetic and carries no real identifiers, so the pipeline skips de-identification
 * for it; an edited or different record never matches and is de-identified as usual.
 */
export function isFixedStudyCaseText(visitTexts: string[]): boolean {
  const normalize = (text: string) => String(text || '').replace(/\r\n/g, '\n').trim();
  const templateTexts = DEFAULT_STUDY_CASE.visits.map((visit) => normalize(visit.soapText));
  return (
    visitTexts.length === templateTexts.length &&
    visitTexts.every((text, index) => normalize(text) === templateTexts[index])
  );
}

export function getStudyCaseTemplate(studyCaseId?: string): StudyCaseTemplate {
  if (!studyCaseId || studyCaseId === DEFAULT_STUDY_CASE_ID || studyCaseId === 'default-study-case') {
    return DEFAULT_STUDY_CASE;
  }

  return DEFAULT_STUDY_CASE;
}
